#!/usr/bin/env python3
"""Build _INDEX.md: one line per note (MOCs first), kept under a size budget.

Usage: python3 build_index.py VAULT [--max-bytes 25000]. Standard library only.
"""
import argparse, re
from pathlib import Path

SKIP = {".git", ".obsidian", ".trash", "node_modules", "_Archive", "_Templates", "_Plantillas", "Templates"}


def fm_of(text):
    if not text.startswith("---") or "\n---" not in text[3:]:
        return {}
    d = {}
    for line in text[3:text.find("\n---", 3)].splitlines():
        if ":" in line and not line.startswith((" ", "-")):
            k, v = line.split(":", 1)
            d[k.strip()] = v.strip().strip(">").strip()
    return d


def first_line(text):
    body = text.split("\n---", 1)[-1] if text.startswith("---") else text
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "---", "<")):
            return line[:110]
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vault")
    ap.add_argument("--max-bytes", type=int, default=25000)
    a = ap.parse_args()
    root = Path(a.vault).expanduser().resolve()
    rows = []
    for p in sorted(root.rglob("*.md")):
        rel = p.relative_to(root)
        if p.name == "_INDEX.md" or any(x in SKIP or x.startswith(".") for x in rel.parts[:-1]):
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        fm = fm_of(text)
        desc = fm.get("description") or first_line(text)
        rows.append((fm.get("type", "note"), p.stem, desc, str(rel)))
    rows.sort(key=lambda r: (r[0] != "moc", r[0], r[1].lower()))
    lines = ["# Vault index", "", "_Auto-generated by obsidian-moc-memory. One line per note. MOCs first._", ""]
    size = sum(len(x) + 1 for x in lines)
    dropped = 0
    for typ, stem, desc, rel in rows:
        line = f"- [[{stem}]] ({typ}) {desc}".rstrip()
        if size + len(line) + 1 > a.max_bytes:
            dropped += 1
            continue
        lines.append(line)
        size += len(line) + 1
    if dropped:
        lines += ["", f"_{dropped} notes omitted for size. Read the MOCs._"]
    (root / "_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {root/'_INDEX.md'} ({len(rows)-dropped}/{len(rows)} notes, {size} bytes)")


if __name__ == "__main__":
    main()
